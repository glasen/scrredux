#!/usr/bin/env python3
"""Generate scr_tracks.h from the Stunt Car Racer remake sources.

usage: tools/gen_scr_tracks.py PATH_TO_StuntCarRacer-X > scr_tracks.h

Reads Tracks/*.bin (804-byte road tables) and the piece shape / height profile tables from Track.cpp.
"""
import os, re, struct, sys

NAMES = ["LittleRamp", "SteppingStones", "HumpBack", "BigRamp", "SkiJump", "DrawBridge", "HighJump", "RollerCoaster"]
TITLES = ["LITTLE RAMP", "STEPPING STONES", "HUMP BACK", "BIG RAMP", "SKI JUMP", "DRAW BRIDGE", "HIGH JUMP", "ROLLER COASTER"]
TPL = {0: (8, "Amiga_Piece0_XZ"), 1: (8, "Amiga_Piece1_XZ"), 3: (8, "Amiga_Piece3_XZ"), 4: (13, "Amiga_Piece4_XZ"),
       6: (9, "Amiga_Piece6_XZ"), 7: (9, "Amiga_Piece7_XZ"), 10: (11, "Amiga_Piece10_XZ")}


def main(root):
    src = open(os.path.join(root, "Track.cpp")).read()
    arr = {m.group(1): bytes(int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]+)", m.group(2)))
           for m in re.finditer(r"static unsigned char (\w+)\[[^\]]*\]\s*=\s*\{([^}]*)\}", src)}
    tbl = re.search(r"Amiga_Piece_Y\[NUM_AMIGA_PIECE_Y\]\s*=\s*\{(.*?)\};", src, re.S).group(1)
    prof = []
    for name, words in re.findall(r"\{(\w+),(TRUE|FALSE),", tbl):
        if name == "NULL":
            prof.append([])
        elif words == "TRUE":
            b = arr[name]; prof.append([((b[i] & 0x7f) << 8) | b[i + 1] for i in range(0, len(b), 2)])
        else:
            prof.append([((v << 1) & 0xe0) | ((v & 0x0f) << 8) for v in arr[name]])
    assert len(prof) == 128

    out = ["/* scr_tracks.h - generated by tools/gen_scr_tracks.py from the Stunt Car Racer remake. Do not edit. */",
           "#define SCR_NTRACKS 8",
           "static const char *const SCR_TITLE[SCR_NTRACKS] = {" + ", ".join(f'"{t}"' for t in TITLES) + "};",
           "/* piece shapes in a 0x800 cube: segment count, then left x,z and right x,z for each cross-section */",
           "static const unsigned char SCR_TPL_NS[11] = {" + ", ".join(str(TPL[t][0] if t in TPL else 0) for t in range(11)) + "};",
           "static const short SCR_TPL_XZ[11][14][4] = {"]
    for t in range(11):
        rows = []
        if t in TPL:
            b = arr[TPL[t][1]]
            v = struct.unpack("<%dh" % (len(b) // 2), b)
            rows = ["{%d,%d,%d,%d}" % tuple(v[i:i + 4]) for i in range(0, len(v), 4)]
        out.append("    {" + (",".join(rows) or "{0}") + "},")
    out.append("};")
    out.append("/* height profiles (one value per cross-section, 1/4 of the x/z unit) */")
    out.append("static const unsigned short SCR_PROF[128][14] = {")
    for p in prof:
        out.append("    {" + (",".join(str(v) for v in p) or "0") + "},")
    out.append("};")
    out.append("/* road tables: pieces, start piece, cube x/z, angle+shape, left/right profile ids, left/right base heights (BE), boost */")
    out.append("static const unsigned char SCR_BIN[SCR_NTRACKS][804] = {")
    for n in NAMES:
        b = open(os.path.join(root, "Tracks", n + ".bin"), "rb").read()
        assert len(b) == 804
        out.append("    { /* %s */" % n)
        for i in range(0, 804, 24):
            out.append("      " + ",".join("0x%02x" % x for x in b[i:i + 24]) + ",")
        out.append("    },")
    out.append("};")
    print("\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
